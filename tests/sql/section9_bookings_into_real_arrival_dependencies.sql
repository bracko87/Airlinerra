-- For booking ONLY, evaluate the real 7-day window at 17:00; the flight
-- departs at 18:00 and arrives at 19:00 UTC. The test workflow resets
-- the clock to 18:00 before actual automatic dispatch.
CREATE OR REPLACE FUNCTION airlinerra_game.section9_verified_berlin_game_hour_v1()
 RETURNS jsonb LANGUAGE sql STABLE AS $fn$
 SELECT jsonb_build_object('authoritativeGameHourAvailable',true,
 'gameDate','2026-11-23','gameHourUtc','2026-11-23 17:00:00+00')
 $fn$;
