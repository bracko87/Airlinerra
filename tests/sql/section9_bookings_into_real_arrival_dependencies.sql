-- Genuine private booking writer joins the EXISTING real signed-arrival
-- disposable flight fixture. Never run against Supabase or shared player data.
-- This tests the same physical flight from passenger inventory to signed
-- departure, fuel custody and final signed arrival, not merely separate jobs.
\set ON_ERROR_STOP on
DO $guard$ BEGIN
 IF current_database()<>'airlinerra_disposable' OR current_user<>'postgres'
 OR to_regclass('airlinerra_game.section9_real_arrival_disposable_dependencies') IS NOT NULL
 OR to_regclass('airlinerra_game.section9_passenger_reservation_batches_v1') IS NULL
 OR to_regclass('airlinerra_game.section9_game_flight_fuel_departure_receipts_v1') IS NULL
 OR to_regclass('airlinerra_game.section9_route_commercial_plans_v1') IS NULL
 THEN RAISE EXCEPTION 'BOOKING_TO_SIGNED_ARRIVAL_REQUIRES_DISPOSABLE_FLIGHT_FIXTURE'; END IF;
END $guard$;

ALTER TABLE airlinerra_game.section9_dated_flight_occurrences_v1
 ADD COLUMN commercial_version integer NOT NULL DEFAULT 1;
ALTER TABLE airlinerra_game.section9_occurrence_capacity_inventory_v1
 ADD COLUMN schedule_id uuid NOT NULL DEFAULT '11111111-1111-4111-8111-111111111111',
 ADD COLUMN status text NOT NULL DEFAULT 'preflight_only';
ALTER TABLE airlinerra_game.section9_route_commercial_plans_v1
 ADD COLUMN economy_fare_usd numeric NOT NULL DEFAULT 50;
ALTER TABLE airlinerra_game.section9_passenger_reservation_batches_v1
 ADD COLUMN id uuid NOT NULL DEFAULT gen_random_uuid(),
 ADD COLUMN reservation_key text,
 ADD COLUMN fare_class text NOT NULL DEFAULT 'economy';
ALTER TABLE airlinerra_game.section9_passenger_reservation_batches_v1
 ADD CONSTRAINT signed_arrival_bookings_key_unique UNIQUE(occurrence_id,reservation_key);
-- Existing two-seat fixture reservations were seeded before this bridge.
-- They are source-labelled as synthetic and are not recognized as payments.
UPDATE airlinerra_game.section9_passenger_reservation_batches_v1
 SET reservation_key='synthetic.legacy.prebook.'||id::text;

